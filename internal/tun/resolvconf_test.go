const origResolvConf = `# Generated by NetworkManager
search lan example.com
nameserver 192.168.1.1
nameserver 198.18.0.53
nameserver fe80::1%eth0
options edns0 trust-ad
`

func TestResolvConf(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	server := netip.MustParseAddr("198.18.0.53")
	read := func() string {
		t.Helper()
		b, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}

	t.Run("set and restore a file", func(t *testing.T) {
		os.WriteFile(path, []byte(origResolvConf), 0o644)
		r := newResolvConf(path)
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		got := read()
		for _, want := range []string{"\nnameserver 198.18.0.53\n", "\nsearch lan example.com\n", "\noptions edns0 trust-ad\n"} {
			if !strings.Contains(got, want) {
				t.Errorf("resolv.conf lacks %q:\n%s", want, got)
			}
		}
		if strings.Contains(got, "192.168.1.1") {
			t.Errorf("resolv.conf still lists the original nameserver:\n%s", got)
		}
		want := []netip.AddrPort{netip.MustParseAddrPort("192.168.1.1:53"), netip.MustParseAddrPort("[fe80::1%eth0]:53")}
		if ups := r.dnsUpstreams(); !slices.Equal(ups, want) {
			t.Errorf("upstreams %v, want %v (tailmux's own address left out)", ups, want)
		}
		if !r.intact() {
			t.Error("not intact right after set")
		}
		// Setting again (a repair) must keep the original, not back up ours.
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		if err := r.restore(); err != nil {
			t.Fatal(err)
		}
		if got := read(); got != origResolvConf {
			t.Errorf("restored:\n%s\nwant:\n%s", got, origResolvConf)
		}
		if _, err := os.Lstat(r.backup); !os.IsNotExist(err) {
			t.Error("backup left behind")
		}
		if r.dnsUpstreams() != nil {
			t.Error("upstreams kept after restore")
		}
	})

	t.Run("a symlink stays a symlink", func(t *testing.T) {
		target := filepath.Join(dir, "managed.conf")
		os.WriteFile(target, []byte(origResolvConf), 0o644)
		os.Remove(path)
		if err := os.Symlink("managed.conf", path); err != nil {
			t.Fatal(err)
		}
		r := newResolvConf(path)
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		if fi, _ := os.Lstat(path); fi.Mode()&os.ModeSymlink != 0 {
			t.Fatal("wrote through the symlink")
		}
		if b, _ := os.ReadFile(target); string(b) != origResolvConf {
			t.Fatal("symlink target changed")
		}
		// The managing program updates its file: upstreams follow.
		os.WriteFile(target, []byte("nameserver 10.0.0.1\n"), 0o644)
		r.set(server)
		if ups := r.dnsUpstreams(); len(ups) != 1 || ups[0].Addr() != netip.MustParseAddr("10.0.0.1") {
			t.Errorf("upstreams %v, want 10.0.0.1", ups)
		}
		if err := r.restore(); err != nil {
			t.Fatal(err)
		}
		if l, err := os.Readlink(path); err != nil || l != "managed.conf" {
			t.Fatalf("symlink not restored: %q %v", l, err)
		}
		os.Remove(path)
	})

	t.Run("a file written over ours wins", func(t *testing.T) {
		os.WriteFile(path, []byte(origResolvConf), 0o644)
		r := newResolvConf(path)
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		const dhcp = "nameserver 10.9.9.9\n"
		os.WriteFile(path, []byte(dhcp), 0o644)
		if r.intact() {
			t.Error("intact after being overwritten")
		}
		// A repair takes the new file as the original.
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		if ups := r.dnsUpstreams(); len(ups) != 1 || ups[0].Addr() != netip.MustParseAddr("10.9.9.9") {
			t.Errorf("upstreams %v, want 10.9.9.9", ups)
		}
		r.restore()
		if got := read(); got != dhcp {
			t.Errorf("restored %q, want %q", got, dhcp)
		}
		// Overwritten and then stopped: the new file stays.
		r.set(server)
		os.WriteFile(path, []byte(origResolvConf), 0o644)
		r.restore()
		if got := read(); got != origResolvConf {
			t.Errorf("restore replaced a file that isn't ours:\n%s", got)
		}
		if _, err := os.Lstat(r.backup); !os.IsNotExist(err) {
			t.Error("stale backup left behind")
		}
	})

	t.Run("crash cleanup", func(t *testing.T) {
		os.WriteFile(path, []byte(origResolvConf), 0o644)
		if err := newResolvConf(path).set(server); err != nil {
			t.Fatal(err)
		}
		// A new process knows nothing but the files.
		if err := newResolvConf(path).restore(); err != nil {
			t.Fatal(err)
		}
		if got := read(); got != origResolvConf {
			t.Errorf("after crash cleanup:\n%s", got)
		}
	})

	t.Run("an unreadable original stays", func(t *testing.T) {
		os.Remove(path)
		os.Symlink("not-there-yet.conf", path)
		r := newResolvConf(path)
		if err := r.set(server); err == nil {
			t.Fatal("took over a resolv.conf it couldn't read")
		}
		if l, err := os.Readlink(path); err != nil || l != "not-there-yet.conf" {
			t.Fatalf("symlink touched: %q %v", l, err)
		}
		if _, err := os.Lstat(r.backup); !os.IsNotExist(err) {
			t.Error("backup made")
		}
		os.Remove(path)
	})

	t.Run("a failed write puts the original back", func(t *testing.T) {
		os.WriteFile(path, []byte(origResolvConf), 0o644)
		r := newResolvConf(path)
		defer func() { writeResolvConf = replaceFile }()
		// An in-place write (bind mount) that fails after truncating.
		writeResolvConf = func(p string, _ []byte) error {
			os.WriteFile(p, nil, 0o644)
			return syscall.EIO
		}
		if err := r.set(server); err == nil {
			t.Fatal("no error")
		}
		if got := read(); got != origResolvConf {
			t.Errorf("after a failed write:\n%s", got)
		}
		if _, err := os.Lstat(r.backup); !os.IsNotExist(err) {
			t.Error("backup left behind")
		}
		if r.dnsUpstreams() != nil {
			t.Error("upstreams set")
		}
	})

	t.Run("a vanished symlink target on repair", func(t *testing.T) {
		target := filepath.Join(dir, "managed.conf")
		os.WriteFile(target, []byte(origResolvConf), 0o644)
		os.Remove(path)
		os.Symlink("managed.conf", path)
		r := newResolvConf(path)
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		os.Remove(target)
		if err := r.set(server); err == nil {
			t.Fatal("kept pointing at tailmux with no upstreams")
		}
		if l, err := os.Readlink(path); err != nil || l != "managed.conf" {
			t.Fatalf("symlink not put back: %q %v", l, err)
		}
		os.Remove(path)
	})

	t.Run("no original", func(t *testing.T) {
		os.Remove(path)
		r := newResolvConf(path)
		if err := r.set(server); err != nil {
			t.Fatal(err)
		}
		if len(r.dnsUpstreams()) != 0 {
			t.Error("upstreams from nowhere")
		}
		r.restore()
		if _, err := os.Lstat(path); !os.IsNotExist(err) {
			t.Error("our file left behind")
		}
	})
}

// TestForwardDNS checks that names no tailnet claims go to the upstream
// nameservers, over UDP and TCP, skipping one that doesn't answer.
func TestForwardDNS(t *testing.T) {
	answer := func(q []byte) []byte {
		var p dnsmessage.Parser
		h, err := p.Start(q)
		if err != nil {
			return nil
		}
		qq, _ := p.Question()
		b := dnsmessage.NewBuilder(nil, dnsmessage.Header{ID: h.ID, Response: true})
		b.StartQuestions()
		b.Question(qq)
		b.StartAnswers()
		b.AResource(dnsmessage.ResourceHeader{Name: qq.Name, Class: dnsmessage.ClassINET, TTL: 60}, dnsmessage.AResource{A: [4]byte{203, 0, 113, 7}})
		out, _ := b.Finish()
		return out
	}
	pc, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer pc.Close()
	port := pc.LocalAddr().(*net.UDPAddr).Port
	ln, err := net.Listen("tcp", net.JoinHostPort("127.0.0.1", strconv.Itoa(port)))
	if err != nil {
		t.Skipf("tcp port %d taken: %v", port, err)
	}
	defer ln.Close()
	go func() {
		buf := make([]byte, 1500)
		for {
			n, addr, err := pc.ReadFrom(buf)
			if err != nil {
				return
			}
			pc.WriteTo(answer(buf[:n]), addr)
		}
	}()
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go func() {
				defer c.Close()
				if q, err := readDNSTCP(c); err == nil {
					writeDNSTCP(c, answer(q))
				}
			}()
		}
	}()
	// Nothing listens on the first one.
	dead, _ := net.ListenPacket("udp", "127.0.0.1:0")
	deadAddr := netip.MustParseAddrPort(dead.LocalAddr().String())
	dead.Close()
	ups := []netip.AddrPort{deadAddr, netip.MustParseAddrPort(pc.LocalAddr().String())}

	cfg := &mux.Config{StateDir: t.TempDir(), Tailnets: []mux.TailnetConfig{{Name: "home"}}} // never started
	if err := cfg.Normalize(); err != nil {
		t.Fatal(err)
	}
	m := mux.New(cfg, mux.Options{MemStore: true})
	defer m.Close()
	e := &Engine{m: m, fake: NewFakeIPs(netip.MustParsePrefix(cfg.TUN.Range), "")}

	query := func() []byte {
		b := dnsmessage.NewBuilder(nil, dnsmessage.Header{ID: 42, RecursionDesired: true})
		b.StartQuestions()
		b.Question(dnsmessage.Question{Name: dnsmessage.MustNewName("example.com."), Type: dnsmessage.TypeA, Class: dnsmessage.ClassINET})
		out, _ := b.Finish()
		return out
	}
	check := func(name string, resp []byte, want dnsmessage.RCode, wantA bool) {
		t.Helper()
		var p dnsmessage.Parser
		h, err := p.Start(resp)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		p.SkipAllQuestions()
		as, _ := p.AllAnswers()
		if h.ID != 42 || h.RCode != want || (len(as) == 1) != wantA {
			t.Errorf("%s: id %d rcode %v answers %d, want rcode %v", name, h.ID, h.RCode, len(as), want)
		}
	}

	check("no upstreams", e.answerDNS(query(), "udp"), dnsmessage.RCodeNameError, false)
	e.upstreams = func() []netip.AddrPort { return ups }
	start := time.Now()
	check("udp", e.answerDNS(query(), "udp"), dnsmessage.RCodeSuccess, true)
	check("tcp", e.answerDNS(query(), "tcp"), dnsmessage.RCodeSuccess, true)
	if d := time.Since(start); d > 6*time.Second {
		t.Errorf("forwarding took %v", d)
	}
	e.upstreams = func() []netip.AddrPort { return ups[:1] }
	check("all upstreams down", e.answerDNS(query(), "udp"), dnsmessage.RCodeServerFailure, false)
}
